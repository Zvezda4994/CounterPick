from pathlib import Path

import numpy as np
import pytest
from scipy.special import expit

from pickem.probs import FitConfig, OddsSheet, StrengthFit, fit_strengths, load_odds_csv
from pickem.probs.fit import simulated_qualify, surrogate_qualify
from pickem.probs.odds_csv import r1_opponent

EXAMPLES = Path(__file__).parents[2] / "examples"
TEAMS = tuple(f"T{i:02d}" for i in range(16))
TRUE_BETA = 3.0


@pytest.fixture(scope="module")
def truth() -> np.ndarray:
    rng = np.random.default_rng(42)
    s = np.sort(rng.normal(scale=0.4, size=16))[::-1]
    s[[2, 10]] = s[[10, 2]]  # a seed that is stronger than its position suggests
    return s - s.mean()


def synthetic_sheet(
    s: np.ndarray, *, r1: bool = True, qualify: bool = True, win: bool = True
) -> OddsSheet:
    """Odds generated by the model itself, with a proportional margin on each book."""
    nan = np.full(16, np.nan)
    r1_odds = 1.0 / (expit(s - s[[r1_opponent(i) for i in range(16)]]) * 1.05)
    q = simulated_qualify(TEAMS, s, 200_000, seed=7)
    share = np.exp(TRUE_BETA * s) / np.exp(TRUE_BETA * s).sum()
    return OddsSheet(
        teams=TEAMS,
        vrs_points=1500 + 100 * s / 0.4,  # consistent with the prior's mean slope
        r1_odds=r1_odds if r1 else nan,
        qualify_odds=1.0 / (q * 1.08) if qualify else nan,
        not_qualify_odds=nan,
        win_major_odds=1.0 / (share * 0.5) if win else nan,
    )


@pytest.fixture(scope="module")
def full_fit(truth: np.ndarray) -> StrengthFit:
    return fit_strengths(synthetic_sheet(truth), FitConfig(method="proportional"))


def test_recovers_known_strengths(truth: np.ndarray, full_fit: StrengthFit) -> None:
    assert full_fit.converged
    assert np.abs(full_fit.strengths - truth).max() < 0.05
    assert full_fit.beta == pytest.approx(TRUE_BETA, abs=0.3)
    assert full_fit.model_qualify == pytest.approx(
        simulated_qualify(TEAMS, truth, 200_000, seed=7), abs=0.02
    )
    assert all(v < 0.5 for v in full_fit.residual_rms.values())


def test_round1_odds_alone_cannot_link_pairs(truth: np.ndarray, full_fit: StrengthFit) -> None:
    only_r1 = fit_strengths(
        synthetic_sheet(truth, qualify=False, win=False), FitConfig(method="proportional")
    )

    def sd_of_difference(fit: StrengthFit, i: int, j: int) -> float:
        c = fit.covariance
        return float(np.sqrt(c[i, i] + c[j, j] - 2 * c[i, j]))

    within_pair = sd_of_difference(only_r1, 0, 8)  # seed 1 v seed 9 met in round 1
    across_pairs = sd_of_difference(only_r1, 0, 1)  # seed 1 v seed 2 did not
    assert within_pair < 0.5 * across_pairs
    assert sd_of_difference(full_fit, 0, 1) < 0.8 * across_pairs  # outrights link the pairs


def test_vrs_only_fit_is_the_prior(truth: np.ndarray) -> None:
    sheet = load_odds_csv(EXAMPLES / "singapore_2026_stage1_odds.csv")
    fit = fit_strengths(sheet)
    z = (sheet.vrs_points - sheet.vrs_points.mean()) / 100
    assert fit.vrs_slope == pytest.approx(0.4, abs=1e-6)
    assert fit.strengths == pytest.approx(0.4 * z, abs=1e-6)
    assert fit.beta is None and fit.residual_rms == {}
    assert fit.correction_rounds == 1


def test_example_sheet_fits_and_reports(tmp_path: Path) -> None:
    fit = fit_strengths(load_odds_csv(EXAMPLES / "example_odds.csv"))
    assert fit.converged and fit.beta is not None
    assert set(fit.residual_rms) == {"round 1", "qualify", "win Major"}
    assert np.all(fit.sd > 0)
    assert float(np.min(np.linalg.eigvalsh(fit.covariance))) > 0
    model = fit.strength_model(spread=0.5, sims_per_draw=200)
    assert model.spread == 0.5 and model.sims_per_draw == 200


def test_surrogate_is_a_fair_coin_for_equal_teams() -> None:
    assert surrogate_qualify(np.zeros(16)) == pytest.approx(np.full(16, 0.5))
    rising = surrogate_qualify(np.linspace(1, -1, 16))
    assert np.all(np.diff(rising) < 0)


def test_config_validation() -> None:
    with pytest.raises(ValueError, match="sigma_match"):
        FitConfig(sigma_match=0)
    with pytest.raises(ValueError, match="method"):
        FitConfig(method="shin")  # type: ignore[arg-type]
    with pytest.raises(ValueError, match="fit_sims"):
        FitConfig(fit_sims=10)
